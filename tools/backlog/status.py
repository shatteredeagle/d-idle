#!/usr/bin/env python3 -I
"""STATUS block and board JSON from backlog/tasks/*.md (replaces `changecheck status` and `changecheck json`).

  python3 -I tools/backlog/status.py status [--write] [--merges N]   print or rewrite the generated block of docs/plan/STATUS.md
  python3 -I tools/backlog/status.py json [--merges N]               the JSON the board /changes page reads (tools/agentstatus/changes.html in the ops repo)

Stdlib only, read-only except --write. Task frontmatter is read directly (the Backlog.md CLI hides our custom keys, docs/backlog-howto.md).
"""
import glob, json, os, re, subprocess, sys, datetime

ROOT = subprocess.run(["git", "rev-parse", "--show-toplevel"], capture_output=True, text=True).stdout.strip() or os.getcwd()
BEGIN = "<!-- statusgen:begin"
END = "<!-- statusgen:end -->"
MERGES_HDR = "### Recent merges"
OPEN = ("proposed", "deferred", "in progress", "in-progress")
GATE_CONTRACTS = ("soak-gates", "fidelity-gate")


def p(*a):
    return os.path.join(ROOT, *a)


def frontmatter(text):
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    d, key = {}, None
    for line in (m.group(1) if m else "").splitlines():
        li = re.match(r"^\s+-\s*(.*)$", line)
        if li and key:
            d.setdefault(key, []).append(li.group(1).strip().strip("\"'"))
            continue
        k = re.match(r"^([A-Za-z_]+):\s*(.*)$", line)
        if k:
            key = k.group(1)
            v = k.group(2).strip()
            d[key] = v.strip("\"'") if v not in ("", "[]") else []
    return d, text[m.end():] if m else text


def tasks():
    out = []
    for f in sorted(glob.glob(p("backlog", "tasks", "*.md"))):
        t = open(f, encoding="utf-8").read()
        d, body = frontmatter(t)
        title = d.get("title", "")
        d["card"] = d.get("card") or title.split(":")[0]
        d["_path"] = os.path.relpath(f, ROOT).replace(os.sep, "/")
        ac = re.findall(r"(?m)^- \[([ xX])\] ", body)
        d["_done"], d["_total"] = sum(1 for c in ac if c != " "), len(ac)
        d["_why"] = (re.search(r"BEGIN -->\n(.*?)\n", body, re.S) or [None, ""])[1]
        out.append(d)
    return out


def is_open(d):
    return str(d.get("status", "")).lower() in OPEN


def merges(n):
    r = subprocess.run(["git", "-C", ROOT, "log", "--merges", "-n%d" % n, "--format=%h%x1f%aI%x1f%s%x1f%b%x1e"], capture_output=True, text=True)
    out = []
    for rec in r.stdout.split("\x1e"):
        f = rec.lstrip("\n").split("\x1f", 3)
        if len(f) == 4:
            t = re.search(r"(?m)^Change:\s*(\S+)", f[3]) or re.search(r"^Merge (?:branch )?'?agent/([\w-]+)", f[2])
            out.append({"hash": f[0], "date": f[1], "subject": f[2], "change": t.group(1) if t else ""})
    return out


def contracts():
    res = []
    for f in sorted(glob.glob(p("docs", "contracts", "*.md"))):
        name = os.path.basename(f)[:-3]
        if name == "README":
            continue
        md = open(f, encoding="utf-8").read()
        reqs = re.split(r"(?m)^### Requirement: ", md)[1:]
        res.append((name, md, reqs))
    return res


def cell(v):
    return "<br>".join("`%s`" % x for x in v) if v else "-"


def block(ts, ms):
    act = [t for t in ts if is_open(t)]
    b = [BEGIN + " (generated by `python3 -I tools/backlog/status.py status --write`; do not edit by hand) -->", "### Active changes"]
    if not act:
        b.append("none")
    else:
        b += ["| task (backlog/tasks) | status | agent | owns | exclusive |", "|---|---|---|---|---|"]
        for t in act:
            b.append("| %s | %s | %s | %s | %s |" % (t["card"], str(t.get("status", "")).lower().replace(" ", "-"),
                     t.get("agent", "-"), cell(t.get("owns") or []), cell(t.get("exclusive") or [])))
    b += ["", "### Gates"]
    for name, _, reqs in contracts():
        b.append("- contract [%s](../contracts/%s.md): %d requirements" % (name, name, len(reqs)))
    b += ["", MERGES_HDR]
    b += ["- %s %s `%s` (%s)" % (m["hash"], m["date"][5:16].replace("T", " "), m["subject"], m["change"] or "-") for m in ms] or ["none"]
    b.append(END)
    return "\n".join(b) + "\n"


def write(ts, ms):
    path = p("docs", "plan", "STATUS.md")
    text = open(path, encoding="utf-8").read()
    i, j = text.find(BEGIN), text.find(END)
    new = block(ts, ms)
    if i < 0 or j < i:
        text = text.rstrip("\n") + "\n\n" + new
    else:
        j += len(END) + (1 if text[j + len(END):j + len(END) + 1] == "\n" else 0)
        text = text[:i] + new + text[j:]
    open(path, "w", encoding="utf-8").write(text)


def needs():
    out = []
    try:
        md = open(p("docs", "needs-you.md"), encoding="utf-8").read()
    except OSError:
        return out
    for line in md.splitlines():
        m = re.match(r"^- \[ \] (.+)$", line.rstrip())
        f = m.group(1).split(" | ") if m else []
        if len(f) >= 5:
            pr = f[1].strip() if f[1].strip() in ("now", "soon", "whenever") else "whenever"
            out.append({"id": f[0].strip(), "priority": pr, "ask": f[2].strip(), "recommendation": f[3].strip(),
                        "since": f[4].strip().removeprefix("since").strip(), "link": f[5].strip() if len(f) > 5 else ""})
    return out


def as_json(ts, ms):
    act = [t for t in ts if is_open(t)]
    d = {"generated": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
         "commit": subprocess.run(["git", "-C", ROOT, "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip(),
         "active": [], "archived": [], "collisions": [], "specs": [], "gates": [], "merges": ms, "warnings": [], "needs_you": needs()}
    for t in act:
        d["active"].append({"id": t["card"], "status": str(t.get("status", "")).lower().replace(" ", "-"), "agent": t.get("agent", ""),
                            "branch": t.get("branch", ""), "worktree": "", "why": t["_why"], "owns": t.get("owns") or [],
                            "exclusive": t.get("exclusive") or [], "gates": [], "tasks_done": t["_done"], "tasks_total": t["_total"], "path": t["_path"]})
    for t in ts:
        if str(t.get("status", "")).lower() == "done":
            d["archived"].append({"id": t["card"], "date": "", "merge": t.get("merge_hash", ""), "result": t.get("result", ""), "path": t["_path"]})
    for name, md, reqs in contracts():
        pur = re.search(r"(?ms)^## Purpose\n(.*?)(?=\n## |\Z)", md)
        d["specs"].append({"name": name, "purpose": " ".join(pur.group(1).split()) if pur else "", "requirements": len(reqs), "path": "docs/contracts/%s.md" % name})
        if name in GATE_CONTRACTS:
            for r in reqs:
                head, _, rest = r.partition("\n")
                text = " ".join(rest.split("#### Scenario")[0].split())
                src = re.search(r"\s*Source:\s*(.+)$", text)
                if src:
                    text = text[:src.start()].strip()
                d["gates"].append({"gate": head.strip(), "threshold": text, "source": "contract " + name + (": " + src.group(1) if src else ""), "value": "-"})
    d["counts"] = {"active": len(d["active"]), "archived": len(d["archived"]), "specs": len(d["specs"]), "collisions": 0, "warnings": 0, "needs_you": len(d["needs_you"])}
    return d


def main(argv):
    if not argv or argv[0] not in ("status", "json"):
        print(__doc__)
        return 2
    n = 10
    if "--merges" in argv:
        n = int(argv[argv.index("--merges") + 1])
    ts, ms = tasks(), merges(n)
    if argv[0] == "json":
        print(json.dumps(as_json(ts, ms), indent=1, ensure_ascii=False))
    elif "--write" in argv:
        write(ts, ms)
        print("docs/plan/STATUS.md block rewritten")
    else:
        print(block(ts, ms), end="")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
