#!/usr/bin/env python3
"""Rebuild docs/INDEX.md by area: one line per tracked markdown doc (title, status banner if any).

docs/research/ and docs/archive/research/ are listed through their own README (hundreds of records);
every other tracked .md under docs/ plus the root docs is listed exactly once. Usage:
  python3 tools/cleanup/build_index.py            # write docs/INDEX.md
  python3 tools/cleanup/build_index.py --check    # exit 1 when INDEX.md is stale or a doc is missing
"""
import os, re, subprocess, sys

root = subprocess.check_output(["git", "rev-parse", "--show-toplevel"], text=True).strip()
os.chdir(root)
files = [f for f in subprocess.check_output(["git", "ls-files", "*.md"], text=True).split("\n") if f]

AREAS = [
    ("product", "Product direction: the automation ladder"),
    ("engine", "Engine and fidelity: d2d, differentials, upstream PRs, deviations"),
    ("bot", "Bot code: capabilities, knobs, contracts, classes and builds"),
    ("ops", "Ops and merge: merge queue, process, CI, worktrees, tooling"),
    ("gates", "Gates and soaks: Gate 0-3, records, runbooks, drills"),
    ("community", "Community: board, contributor guides, public page"),
    ("archive", "Archive and history"),
    ("root", "Root documents"),
]

def area(f):
    b = os.path.basename(f)
    if "/" not in f:
        return "root"
    if f.startswith("docs/archive/"):
        return "archive"
    d = f.split("/")[1] if f.count("/") > 1 else ""
    if d in ("community", "contributing"):
        return "community"
    if d in ("plan", "grills", "adr", "goals", "net") or b in ("decisions.md", "roadmap.md", "watch.md"):
        return "product"
    if d in ("soaks", "probes", "milestones") or re.match(r"(soak|gate|g1-log|livedrills|liveruns|livecheck|kitgate|bossgate|gear-gate|d2d-soak|d2d-baselines|d2d-run|d2d-loop|dwm4|stall|sentinel)", b):
        return "gates"
    if d in ("process", "agents", "d2d-container", "stream", "publish") or re.match(
        r"(ci|cards|OWNERS|BACKLOG|backlog|release|setup|boardhost|api-agent|container|nas-container|publish|branding|licensing|wineclean|troubleshooting|quickstart|streamctl|launch|fleet|multi|oog|sandbox|saves|fixtures|fixstatus|fixbigfiles|botlogs|open-findings|review-strategy|sentinel|display)", b):
        return "ops"
    if d in ("sme", "coverage", "contracts") and d != "contracts":
        return "engine"
    if d in ("contracts", "classes", "progression"):
        return "bot"
    if re.match(r"(d2d|d2-|orig-|fork|timescale|mem|upstreamsync|decomp|replay|snaplib|hastpdump|killgap|lockstep|primitives|probes|data|map|inventory|viewport|d2dctl|rtleave|nowall|potion-bug|spec-skip)", b):
        return "engine"
    return "bot"

def meta(f):
    title, banner = "", ""
    try:
        for i, line in enumerate(open(f, encoding="utf-8", errors="replace")):
            if i > 40:
                break
            if not title and line.startswith("# "):
                title = line[2:].strip()
            if not banner and line.startswith("> status:"):
                banner = line[len("> status:"):].strip()
            if title and banner:
                break
    except OSError:
        pass
    strip = lambda x: re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", x)
    title = re.sub(r"\s+", " ", strip(title))
    banner = re.sub(r"\s+", " ", strip(banner))
    if len(banner) > 110:
        banner = banner[:107].rsplit(" ", 1)[0] + "..."
    if len(title) > 110:
        title = title[:107].rsplit(" ", 1)[0] + "..."
    return title or os.path.splitext(os.path.basename(f))[0], banner

def link(f):
    return os.path.relpath(f, "docs") if f.startswith("docs/") else "../" + f

skip = lambda f: (f == "docs/INDEX.md" or f.startswith("docs/research/") or f.startswith("docs/archive/research/")
                  or f.startswith("backlog/") or f.startswith("openspec/") or f.startswith("web/") or f.startswith("tools/")
                  or f.startswith("internal/") or f.startswith("cmd/") or f.startswith("deploy/") or f.startswith("packaging/")
                  or f.startswith("assets/") or f.endswith("THIRD_PARTY.md"))

buckets = {k: [] for k, _ in AREAS}
for f in sorted(files):
    if skip(f) or not (f.startswith("docs/") or "/" not in f):
        continue
    buckets[area(f)].append(f)

out = []
out.append("# docs/INDEX.md: map of docs/ by area\n")
out.append("> status: generated by `python3 tools/cleanup/build_index.py` (cleanup batch B, 2026-11-05); do not edit by hand, edit the doc's own title or `> status:` line instead. "
           "Start with [START-HERE.md](START-HERE.md). The hand-written one-line-per-doc map of 2026-10-30 is kept as [archive/INDEX-20261030.md](archive/INDEX-20261030.md).\n")
out.append("Research records (about 330 files, by topic): [research/README.md](research/README.md); finished research moved out of the way: [archive/research/](archive/research/). "
           "Probe logs and soak records live in [probes/](probes/) and [soaks/](soaks/). Counts that change are never copied here: see `git log`, [g1-log.md](g1-log.md) and the generated block of [plan/STATUS.md](plan/STATUS.md).\n")
out.append("<!-- BEGIN GENERATED INDEX -->\n")
total = 0
for key, name in AREAS:
    fs = buckets[key]
    out.append(f"## {name}\n")
    cur = None
    for f in fs:
        sub = os.path.dirname(f)
        if sub != cur:
            cur = sub
            if sub and sub != "docs":
                out.append(f"\n`{sub.replace('docs/', '', 1)}/`\n")
        t, b = meta(f)
        line = f"- [{os.path.basename(f) if os.path.basename(f) != 'README.md' else sub.rsplit('/', 1)[-1] + '/README.md'}]({link(f)}): {t}"
        if b:
            line += f" (status: {b})"
        out.append(line)
        total += 1
    out.append("")
out.append("<!-- END GENERATED INDEX -->")
text = "\n".join(out) + "\n"
text = text.replace("](../README", "](../README")
if "--check" in sys.argv:
    cur = open("docs/INDEX.md", encoding="utf-8").read() if os.path.exists("docs/INDEX.md") else ""
    sys.exit(0 if cur == text else 1)
open("docs/INDEX.md", "w", encoding="utf-8").write(text)
print(f"INDEX.md written: {total} docs listed")
