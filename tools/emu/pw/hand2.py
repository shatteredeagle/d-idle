def sq(ux, uy, h): return {(x, y): 1 for y in range(uy-h, uy+h+1) for x in range(ux-h, ux+h+1)}
cases = [
 (0, 100, 100, sq(100,100,48)),
 (1, 100, 100, {**sq(100,100,48), (51,51):1}),
 (2, 100, 100, {**sq(100,100,48), (51,51):1,(149,51):1}),
 (3, 100, 100, {**sq(100,100,48), (51,51):1,(149,51):1,(51,149):1}),
 (4, 100, 100, sq(100,100,40)),
 (5, 100, 100, sq(100,100,30)),
 (6, 100, 100, sq(100,100,10)),
 (7, 90, 90, sq(90,90,10)),
 (8, 110, 110, sq(110,110,10)),
 (9, 100, 100, sq(100,100,15)),
]
for cid, ux, uy, w in cases:
    flat = " ".join(f"{x} {y} {v}" for (x, y), v in sorted(w.items()))
    print(f"{cid} 1 {ux} {uy} {ux} {uy} {len(w)} {flat}".rstrip())
