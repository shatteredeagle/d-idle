# Build (or check) the persistent GAME.EXE EMULATOR IMAGE on the worker host. Docs: docs/emu-image.md.
#   tools/emu/emu_setup.sh setup     create / repair the image (idempotent, read-only sources, < 10 min)
#   tools/emu/emu_setup.sh verify    sha256 list + python imports + one cheap oracle (drlg seeds), exit 0 = good
#   tools/emu/emu_setup.sh env       print the exports (the same text as $D2_EMU_DIR/env.sh)
# Run it on the worker host:  labrun <host> -- bash tools/emu/emu_setup.sh setup   (from inside the worktree)
# Image dir: $D2_EMU_DIR, default ~/d2d-lab/emu. NEVER under /tmp. The worker-host cleanup must keep it (docs/process/cleanup-keep-list.md).
# Sources (all only READ, never modified; the image holds copies / hard links):
#   D2_GAME_DIR   the user's own installed 1.14d game folder (Game.exe + MPQs)
#   D2_DATA       the MPQ folder d2d uses (default ~/d2d-lab/data)
#   D2_PATCH_SRC  LODPatch_114d.exe (mpq-cat reads the 1.14d tables out of it)
#   D2_UPSTREAM_SRC  a git checkout/clone of the upstream emulator repo (tools/emu); default: first existing of
#                    ~/d2d-lab/pr/gaps, ~/d2d-lab/src, else the public upstream URL
#   D2_UPSTREAM_REF  commit to pin (default 8a3cb678)
#   MPQCAT        a built mpq-cat (default: copy from ~/d2d-lab/pr/gaps/build or ~/d2d-lab/src/build)
set -eu
E=${D2_EMU_DIR:-$HOME/d2d-lab/emu}
GAME_DIR=${D2_GAME_DIR:-$HOME/Games/d2lod-inst/i1/proton/pfx/drive_c/Program Files (x86)/Diablo II}
DATA=${D2_DATA:-$HOME/d2d-lab/data}
PATCH_SRC=${D2_PATCH_SRC:-$HOME/Downloads/LODPatch_114d.exe}
REF=${D2_UPSTREAM_REF:-8a3cb678}
URL=https://github.com/psi29a/d2decomped
case $E in /tmp/*|/var/tmp/*) echo "emu_setup: refusing a volatile D2_EMU_DIR ($E)" >&2; exit 2 ;; esac

envtext() {
cat <<EOT
# generated by tools/emu/emu_setup.sh: source this file
export D2_EMU_DIR="$E"
export D2_MPQ_DIR="$E/mpq"
export D2_PATCH_INSTALLER="$E/patch/LODPatch_114d.exe"
export UP="$E/upstream"
export EMU="$E/upstream/tools/emu"
export PY="$E/venv/bin/python"
export MPQCAT="$E/upstream/build/tools/mpq-cat/mpq-cat"
export GAMEEXE="$E/casttrace/game.exe"
EOT
}

hashfiles() { # files whose hashes are recorded in docs/emu-image.md
	( cd "$E" && sha256sum mpq/bin/game.exe casttrace/game.exe patch/LODPatch_114d.exe mpq/Patch_D2.mpq \
		mpq/d2data.mpq mpq/d2exp.mpq mpq/d2char.mpq upstream/build/tools/mpq-cat/mpq-cat )
}

link_or_copy() { # hard link (survives deletion of the source), else copy
	[ -e "$2" ] && return 0
	ln "$1" "$2" 2>/dev/null || cp -p "$1" "$2"
}

do_setup() {
	[ -f "$GAME_DIR/Game.exe" ] || { echo "emu_setup: no Game.exe in $GAME_DIR (set D2_GAME_DIR)" >&2; exit 2; }
	[ -d "$DATA" ] || { echo "emu_setup: no MPQ dir $DATA (set D2_DATA)" >&2; exit 2; }
	[ -f "$PATCH_SRC" ] || { echo "emu_setup: no $PATCH_SRC (set D2_PATCH_SRC)" >&2; exit 2; }
	mkdir -p "$E/mpq/bin" "$E/casttrace" "$E/patch"
	for f in "$DATA"/*.mpq "$DATA"/*.MPQ; do [ -f "$f" ] && link_or_copy "$f" "$E/mpq/$(basename "$f")"; done
	# mpq-cat sees the 1.14d patch layer only under the lowercase name
	[ -e "$E/mpq/patch_d2.mpq" ] || { [ -f "$E/mpq/Patch_D2.mpq" ] && ln "$E/mpq/Patch_D2.mpq" "$E/mpq/patch_d2.mpq"; }
	for d in mpq/bin casttrace; do
		[ -f "$E/$d/game.exe" ] || { cp "$GAME_DIR/Game.exe" "$E/$d/game.exe"; chmod a-w "$E/$d/game.exe"; }
	done
	[ -f "$E/patch/LODPatch_114d.exe" ] || { cp "$PATCH_SRC" "$E/patch/LODPatch_114d.exe"; chmod a-w "$E/patch/LODPatch_114d.exe"; }
	if [ ! -d "$E/upstream/.git" ]; then
		src=${D2_UPSTREAM_SRC:-}
		if [ -z "$src" ]; then for c in "$HOME/d2d-lab/pr/gaps" "$HOME/d2d-lab/src"; do [ -d "$c/.git" ] && src=$c && break; done; fi
		git clone --quiet "${src:-$URL}" "$E/upstream"
	fi
	git -C "$E/upstream" -c advice.detachedHead=false checkout --quiet "$REF"
	m="$E/upstream/build/tools/mpq-cat/mpq-cat"
	if [ ! -x "$m" ]; then
		mkdir -p "$(dirname "$m")"
		for c in "${MPQCAT:-}" "$HOME/d2d-lab/pr/gaps/build/tools/mpq-cat/mpq-cat" "$HOME/d2d-lab/src/build/tools/mpq-cat/mpq-cat"; do
			[ -n "$c" ] && [ -x "$c" ] && { cp "$c" "$m"; break; }
		done
		[ -x "$m" ] || { echo "emu_setup: no mpq-cat to copy; build it: cd $E/upstream && cmake -B build -G Ninja && cmake --build build --target mpq-cat (needs network for StormLib)" >&2; exit 3; }
	fi
	if [ ! -x "$E/venv/bin/python" ] || ! "$E/venv/bin/python" -c 'import unicorn,pefile,capstone' 2>/dev/null; then
		python3 -m venv "$E/venv"
		whl=$(ls "$HOME"/d2d-lab/src/unicorn-*.whl 2>/dev/null | head -1 || true)
		"$E/venv/bin/pip" install --quiet 'capstone>=5.0.9' 'pefile>=2024.8.26' "${whl:-unicorn>=2.1.4}"
	fi
	envtext > "$E/env.sh"
	hashfiles > "$E/SHA256SUMS"
	echo "emu image ready: $E ($(du -sh "$E" | cut -f1) incl. hard-linked MPQs)"
	echo "next: tools/emu/emu_setup.sh verify"
}

do_verify() {
	[ -d "$E" ] || { echo "verify FAIL: no $E (run setup)"; exit 1; }
	[ -f "$E/SHA256SUMS" ] && ( cd "$E" && sha256sum -c --quiet SHA256SUMS ) && echo "sha256: ok" || { echo "verify FAIL: sha256"; exit 1; }
	[ "$(md5sum "$E/mpq/bin/game.exe" | cut -c1-8)" = 2b3600c1 ] || { echo "verify FAIL: game.exe is not the 1.14d build (md5 2b3600c1...)"; exit 1; }
	. "$E/env.sh"
	"$PY" -c 'import unicorn,pefile,capstone; print("python imports ok, unicorn", unicorn.__version__)'
	here=$(cd "$(dirname "$0")" && pwd)
	cd "$EMU"
	# oracle 1: game.exe's XP level-gap step over the full grid, against our port (docs/research/xp-gold-trace.md): 119,790 lines, 0 differ
	PYTHONPATH="$here:$EMU" nice "$PY" "$here/xp_award.py" grid > "$E/.verify-grid.txt"
	n=$(wc -l < "$E/.verify-grid.txt")
	d=$(PYTHONPATH="$here:$EMU" "$PY" "$here/xpg_model.py" check "$E/.verify-grid.txt" | tail -1)
	rm -f "$E/.verify-grid.txt"
	echo "xp grid lines: $n; xpg_model check: $d"
	[ "$n" = 119790 ] && case $d in *" 0"*|*"0 "*|*"0") echo "verify OK" ;; *) echo "verify FAIL: grid differs"; exit 1 ;; esac
}

case ${1:-} in
setup) do_setup ;;
verify) do_verify ;;
env) envtext ;;
*) sed -n '2,7p' "$0"; exit 2 ;;
esac
