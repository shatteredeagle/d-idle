// defaultGolden holds one file per hero profile (setup-banked.tsv, setup-played.tsv): for every scenario and class the
// prepared hero (level, unspent points, main attack and its hand, the number of player commands that spend the points)
// and a hash of the whole setup. A change that moves a hero or a setup it did not mean to shows as rows of these files
// in review (the blast radius the 2026-11-27 default change did not show), and fails the smoke until regenerated.
const defaultGolden = "tools/provingground/golden"

const goldenHeader = "# GENERATED by `go run ./cmd/d2scenario setup-golden -write`; never edit by hand.\n" +
	"# scenario\tclass\tlevel\tstat_pts\tskill_pts\tattack\thand\tspend_cmds\tsetup_sha\n"

// goldenFiles renders the golden files (profile to content). The hero resolves with the name tables (no game files), so
// the attack is a name and the hash covers the library's verbs with name-table ids; the setup is BuildSetup's, whole.
func goldenFiles(scs []scenario.Scenario) (map[string]string, error) {
	rows := map[string][]string{scenario.HeroBanked: nil, scenario.HeroPlayed: nil}
	for _, s := range scs {
		for _, class := range s.Matrix.Classes {
			su, err := scenario.BuildSetup(s, class, s.Matrix.Seeds[0])
			if err != nil {
				return nil, err
			}
			h, _ := scenarioHero(s, class, hero.NameTables())
			attack, hand, spend := "-", "-", 0
			var lines []string
			if su.HeroProfile == scenario.HeroPlayed {
				if h.Attack != "" {
					attack = h.Attack
				}
				for _, v := range h.Verbs {
					if v.Write {
						continue
					}
					lines = append(lines, v.Line)
					spend++
					if f := strings.Fields(v.Line); len(f) == 4 && f[1] == "select" { // cmd select <skill> <left>
						hand = map[bool]string{true: "right", false: "left"}[f[3] == "0"]
					}
				}
			}
			b, err := json.Marshal(struct {
				Setup scenario.Setup
				Hero  []string
			}{su, lines})
			if err != nil {
				return nil, err
			}
			sum := sha256.Sum256(b)
			rows[su.HeroProfile] = append(rows[su.HeroProfile], fmt.Sprintf("%s\t%s\t%d\t%d\t%d\t%s\t%s\t%d\t%s",
				s.ID, class, h.Level, h.StatPts, h.SkillPts, attack, hand, spend, hex.EncodeToString(sum[:6])))
		}
	}
	out := map[string]string{}
	for p, r := range rows {
		sort.Strings(r)
		out[p] = goldenHeader + strings.Join(r, "\n") + "\n"
	}
	return out, nil
}

// checkGolden compares the files in dir with the scenarios; the error names the rows that moved.
func checkGolden(scs []scenario.Scenario, dir string) error {
	want, err := goldenFiles(scs)
	if err != nil {
		return err
	}
	var bad []string
	for _, p := range []string{scenario.HeroBanked, scenario.HeroPlayed} {
		path := filepath.Join(dir, "setup-"+p+".tsv")
		b, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		have := map[string]bool{}
		for _, l := range strings.Split(string(b), "\n") {
			have[l] = true
		}
		n := 0
		for _, l := range strings.Split(want[p], "\n") {
			if !have[l] {
				if n++; n <= 5 {
					bad = append(bad, path+": "+strings.ReplaceAll(l, "\t", " "))
				}
			}
			delete(have, l)
		}
		if n > 5 {
			bad = append(bad, fmt.Sprintf("%s: and %d more rows", path, n-5))
		}
		if n == 0 && len(have) > 0 {
			bad = append(bad, fmt.Sprintf("%s: %d rows of scenarios that are gone or changed profile", path, len(have)))
		}
	}
	if len(bad) > 0 {
		return fmt.Errorf("setup golden files differ (a hero or a setup moved; if meant, regenerate with `go run ./cmd/d2scenario setup-golden -write` and review the rows):\n  %s", strings.Join(bad, "\n  "))
	}
	return nil
}

func cmdSetupGolden(args []string, w io.Writer) error {
	fs := newFlags("setup-golden")
	dir := fs.String("dir", defaultDir, "scenario directory")
	golden := fs.String("golden", defaultGolden, "golden file directory")
	write := fs.Bool("write", false, "regenerate the files instead of checking them")
	if _, err := parseArgs(fs, args); err != nil {
		return err
	}
	scs, err := loadAll(*dir)
	if err != nil {
		return err
	}
	if !*write {
		if err := checkGolden(scs, *golden); err != nil {
			return err
		}
		fmt.Fprintln(w, "setup golden ok")
		return nil
	}
	files, err := goldenFiles(scs)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(*golden, 0o755); err != nil {
		return err
	}
	for p, body := range files {
		if err := os.WriteFile(filepath.Join(*golden, "setup-"+p+".tsv"), []byte(body), 0o644); err != nil {
			return err
		}
		fmt.Fprintf(w, "setup-%s.tsv: %d rows\n", p, strings.Count(body, "\n")-2)
	}
	return nil
}
