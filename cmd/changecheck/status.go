package main

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const (
	beginMark = "<!-- statusgen:begin"
	endMark   = "<!-- statusgen:end -->"
	mergesHdr = "### Recent merges"
)

// renderBlock builds the generated STATUS block: active changes, gates (cards and specs), recent merges.
func renderBlock(root string, cards []*Card, merges []Merge) string {
	var b strings.Builder
	b.WriteString(beginMark + " (generated by `go run ./cmd/changecheck status -write`; do not edit by hand) -->\n")
	b.WriteString("### Active changes\n")
	var act []*Card
	for _, c := range cards {
		if c.Active() {
			act = append(act, c)
		}
	}
	if len(act) == 0 {
		b.WriteString("none\n")
	} else {
		b.WriteString("| change | status | agent | owns | exclusive |\n|---|---|---|---|---|\n")
		for _, c := range act {
			fmt.Fprintf(&b, "| [%s](../../openspec/changes/%s/) | %s | %s | %s | %s |\n", c.ID, c.ID, c.Status(), c.Agent(), cell(c.Owns()), cell(c.Exclusive()))
		}
	}
	b.WriteString("\n### Gates\n")
	names, counts := specSummaries(root)
	for _, n := range names {
		fmt.Fprintf(&b, "- spec [%s](../../openspec/specs/%s/spec.md): %d requirements\n", n, n, counts[n])
	}
	for _, c := range act {
		for _, g := range c.Gates() {
			fmt.Fprintf(&b, "- change %s: %s\n", c.ID, g)
		}
	}
	b.WriteString("\n" + mergesHdr + "\n")
	if len(merges) == 0 {
		b.WriteString("none\n")
	}
	for _, m := range merges {
		id := changeID(m)
		if id == "" {
			id = "-"
		}
		fmt.Fprintf(&b, "- %s %s `%s` (%s)\n", m.Hash, m.Date, m.Subject, id)
	}
	b.WriteString(endMark + "\n")
	return b.String()
}

func cell(v []string) string {
	if len(v) == 0 {
		return "-"
	}
	s := make([]string, len(v))
	for i, x := range v {
		s[i] = "`" + x + "`"
	}
	return strings.Join(s, "<br>")
}

// splitBlock returns text before, the block, and text after; ok is false when markers are missing.
func splitBlock(text string) (before, block, after string, ok bool) {
	i := strings.Index(text, beginMark)
	j := strings.Index(text, endMark)
	if i < 0 || j < i {
		return text, "", "", false
	}
	j += len(endMark)
	if j < len(text) && text[j] == '\n' {
		j++
	}
	return text[:i], text[i:j], text[j:], true
}

// stable drops the merge list, which changes with every merge and would make the check always stale.
func stable(block string) string {
	if i := strings.Index(block, mergesHdr); i >= 0 {
		return block[:i]
	}
	return block
}

func statusPath(root string) string { return filepath.Join(root, "docs", "plan", "STATUS.md") }

// writeStatus regenerates the block in STATUS.md (appending markers when absent).
func writeStatus(root string, cards []*Card, n int) error {
	ms, err := gitMerges(root, "", n)
	if err != nil {
		return err
	}
	text, _ := readFile(statusPath(root))
	blk := renderBlock(root, cards, ms)
	before, _, after, ok := splitBlock(text)
	if !ok {
		before, after = strings.TrimRight(text, "\n")+"\n\n", ""
	}
	return os.WriteFile(statusPath(root), []byte(before+blk+after), 0o644)
}

// checkStatus warns when the card-derived part of the block differs from what the cards say.
func checkStatus(root string, cards []*Card) []Finding {
	text, err := readFile(statusPath(root))
	if err != nil {
		return []Finding{{"status", "docs/plan/STATUS.md missing"}}
	}
	_, have, _, ok := splitBlock(text)
	if !ok {
		return []Finding{{"status", "STATUS.md has no generated block (run changecheck status -write)"}}
	}
	if stable(have) != stable(renderBlock(root, cards, nil)) {
		return []Finding{{"status", "generated block of STATUS.md is out of date (run changecheck status -write)"}}
	}
	return nil
}

func sortFindings(fs []Finding) {
	sort.SliceStable(fs, func(i, j int) bool { return fs[i].Check < fs[j].Check })
}
