// DefaultExpForLevel returns total exp to reach lvl (levels 1..99).
func DefaultExpForLevel(lvl int) (uint32, bool) {
	if lvl < 1 || lvl >= len(expTable) {
		return 0, false
	}
	return expTable[lvl], true
}
